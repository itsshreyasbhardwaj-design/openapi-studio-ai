function packageJson(spec: SdkSpec, language: "typescript" | "javascript"): string {
  return `${JSON.stringify(
    {
      name: spec.packageName,
      version: spec.version,
      description: spec.description,
      type: "module",
      main: language === "typescript" ? "dist/index.js" : "src/index.js",
      types: language === "typescript" ? "dist/index.d.ts" : undefined,
      files: language === "typescript" ? ["dist"] : ["src"],
      scripts: language === "typescript" ? { build: "tsc -p tsconfig.json" } : {},
      license: "MIT",
    },
    null,
    2,
  )}\n`;
}

export function generateTypeScript(spec: SdkSpec): GeneratedSdk {
  const files: GeneratedFile[] = [
    { path: "src/models.ts", contents: modelsFile(spec) },
    { path: "src/client.ts", contents: clientFile(spec) },
    {
      path: "src/index.ts",
      contents: `export * from "./client";\nexport * from "./models";\n`,
    },
    { path: "package.json", contents: packageJson(spec, "typescript") },
    {
      path: "tsconfig.json",
      contents: `${JSON.stringify(
        {
          compilerOptions: {
            target: "ES2022",
            module: "ESNext",
            moduleResolution: "bundler",
            declaration: true,
            strict: true,
            outDir: "dist",
            lib: ["ES2022", "DOM"],
          },
          include: ["src"],
        },
        null,
        2,
      )}\n`,
    },
    { path: "README.md", contents: readmeFile(spec, "typescript") },
  ];

  return {
    language: "typescript",
    files,
    entryPoint: "src/client.ts",
    installCommand: `npm install ${spec.packageName}`,
  };
}

